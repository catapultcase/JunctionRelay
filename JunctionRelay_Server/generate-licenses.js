// Read the first existing file from a list of candidate paths.
function readFirst(...candidates) {
  for (const p of candidates) {
    if (p && fs.existsSync(p)) {
      try { return fs.readFileSync(p, 'utf8'); } catch { /* try next */ }
    }
  }
  return null;
}

// Build the vendored-JunctionRelay-packages license section. The FrameEngine
// artifact is proprietary (its own LICENSE) and carries its own bundled
// third-party licenses, which must appear in this aggregate. Styles is GPL-3.
function buildVendorSection() {
  const feDir = ['junctionrelaywebui/vendor/@junctionrelay/frameengine',
                 'vendor/@junctionrelay/frameengine'];
  const feThirdParty = readFirst(...feDir.map(d => path.join(d, 'THIRD-PARTY-LICENSES.txt')));
  const feLicense = readFirst(...feDir.map(d => path.join(d, 'LICENSE')));
  const stylesLicense = readFirst('junctionrelaywebui/vendor/@junctionrelay/styles/LICENSE',
                                  'vendor/@junctionrelay/styles/LICENSE');

  let out = `================================================================================

VENDORED JUNCTIONRELAY PACKAGES
================================================================================

--------------------------------------------------------------------------------
@junctionrelay/frameengine (Proprietary)
--------------------------------------------------------------------------------
The JunctionRelay FrameEngine is proprietary, distributed as a pre-built
vendored artifact. The GNU GPL that covers JunctionRelay Server grants no
rights to this component. Its license:

`;
  out += (feLicense ? feLicense.trim() : '(FrameEngine LICENSE not found)') + `\n\n`;

  if (feThirdParty) {
    out += `The FrameEngine artifact bundles the following third-party components:\n\n`;
    out += feThirdParty.trim() + `\n\n`;
  }

  out += `--------------------------------------------------------------------------------
@junctionrelay/styles (GPL-3.0-or-later)
--------------------------------------------------------------------------------
Copyright (C) 2024-present Jonathan Mills, CatapultCase.

`;
  out += (stylesLicense ? stylesLicense.trim() + `\n\n` : '');
  return out;
}

