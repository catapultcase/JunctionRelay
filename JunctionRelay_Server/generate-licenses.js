// Process each Node.js package
const packages = Object.keys(nodeLicensesData).sort();
let count = 0;

for (const pkg of packages) {
  const data = nodeLicensesData[pkg];

  output += `--------------------------------------------------------------------------------\n`;
  output += `${pkg}\n`;
  output += `--------------------------------------------------------------------------------\n`;
  output += `License: ${data.licenses}\n`;
  if (data.repository) output += `Repository: ${data.repository}\n`;
  if (data.publisher) output += `Publisher: ${data.publisher}\n`;
  output += `\n`;

  // Read and include license file if it exists
  if (data.licenseFile && fs.existsSync(data.licenseFile)) {
    try {
      const licenseText = fs.readFileSync(data.licenseFile, 'utf8');
      output += licenseText;
      output += `\n\n`;
    } catch (err) {
      output += `(License file could not be read)\n\n`;
    }
  } else {
    output += `(No license file found)\n\n`;
  }

  count++;
}

